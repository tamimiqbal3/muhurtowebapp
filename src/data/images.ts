import type { ImageRef } from "../lib/types";

// All photographs are free-to-use images from Pexels (https://www.pexels.com/license/).
// IDs were taken from Pexels search/profile pages, many by Bangladeshi photographers.
// The custom image loader appends the width parameter at render time.
export function px(id: number, alt: string): ImageRef {
  return { src: `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg`, alt };
}

/** A freely licensed photo from Wikimedia Commons, credited to its author with a link to its licence page. */
export function wm(src: string, alt: string, author: string, source: string): ImageRef {
  return { src, alt, credit: { author, source } };
}

